"""
Morphix Desktop Companion Robot - Gemini JSON Parser
====================================================
File: src/gemini/json_parser.py
Description:
    Cleans up and extracts structured JSON mappings from Gemini outputs,
    safely removing surrounding markdown block wrappers.
"""

import json
import re
from typing import Any, Dict, Optional


class JsonParser:
    """
    Sanitizes raw response strings to parse internal JSON maps.
    """

    @staticmethod
    def parse_gemini_json(raw_text: str) -> Optional[Dict[str, Any]]:
        """
        Parses JSON response, ignoring potential markdown codeblock wrappers.

        :param raw_text: Raw string generated by Gemini.
        :return: Decoded JSON dictionary if successful, None otherwise.
        """
        if not raw_text:
            return None

        cleaned = raw_text.strip()
        # Regex to strip leading/trailing ```json ... ``` or ``` ... ```
        if cleaned.startswith("```"):
            match = re.search(r"^(?:```json\s*|```\s*)(.*?)```$", cleaned, re.DOTALL | re.IGNORECASE)
            if match:
                cleaned = match.group(1).strip()

        try:
            parsed = json.loads(cleaned)
            if isinstance(parsed, dict):
                return parsed
        except json.JSONDecodeError:
            pass
        return None
